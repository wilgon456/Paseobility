#!/usr/bin/env python3
"""Offline check that skills and plugin only reference real Paseo CLI surface.

The surface recorded in docs/paseo-cli-surface.json is generated by
scripts/paseo-cli-surface.py from the installed CLI help tree. This test never
runs the CLI and needs no Paseo install, so it runs in CI unchanged.
"""
import bisect
import json
from pathlib import Path
import re
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "docs" / "paseo-cli-surface.json"

CODE_SPAN = re.compile(r"`([^`\n]+)`")
PASEO_START = re.compile(r"\bpaseo(?=\s)")
CLI_START = re.compile(r"\bcli\s+\S+\s+--\s+")
TOKEN = re.compile(r"[A-Za-z0-9_<>{}\[\].:=/~-]+")
FLAG = re.compile(r"^(--[A-Za-z][A-Za-z0-9-]*|-[A-Za-z0-9])$")
ELLIPSIS = {"...", "…"}

JS_IDENTIFIER = re.compile(r"[A-Za-z_$][\w$]*(?:\.[\w$]+)*|\d+")
PY_IDENTIFIER = re.compile(r"[A-Za-z_]\w*(?:\.[\w]+)*|\d+")
CLI_EVIDENCE = re.compile(
    r"""["']paseo(?:\.cmd)?["']|/paseo\b|\b(?:resolve)?PaseoCli\b|\bBUNDLED_PASEO_CLI\b|\bexecute\s*\(\s*cli\s*,""")

# References that are deliberately version-gated and cannot be recorded from
# the snapshot version. Each entry needs a reason; keep this list small.
# The snapshot comes from Paseo 0.13.0, a strict superset of the 0.12.0 surface
# (0.13 only adds the `host` group). Skills mark `host` commands as 0.13+.
VERSION_GATED_COMMANDS = {}
VERSION_GATED_FLAGS = {
    ("agent ls", "--background"): "0.12+ flag; older hosts reject it on purpose",
    ("workspace ls", "--background"): "0.12+ flag; older hosts reject it on purpose",
}

SCRIPT_SUFFIXES = {".js", ".mjs", ".cjs", ".ts", ".mts", ".tsx", ".py"}


def load_surface(path=SNAPSHOT):
    return json.loads(path.read_text(encoding="utf-8"))


def tokens_after(text, start):
    tokens = []
    index = start
    while index < len(text) and text[index].isspace():
        index += 1
    while index < len(text):
        match = TOKEN.match(text, index)
        if not match:
            break
        token = match.group(0).rstrip(".,;:")
        if token:
            tokens.append(token)
        index = match.end()
        if index == len(text):
            break
        if not text[index].isspace():
            break
        while index < len(text) and text[index].isspace():
            index += 1
    return tokens


def segment_invocations(text):
    """Return paseo argument token lists found in one line or code span."""
    found = []
    for match in PASEO_START.finditer(text):
        tokens = tokens_after(text, match.end())
        if tokens:
            found.append(tokens)
    for match in CLI_START.finditer(text):
        tokens = tokens_after(text, match.end())
        if tokens:
            found.append(tokens)
    return found


def document_invocations(text):
    """Return (line number, argument tokens) for paseo invocations in docs."""
    found = []
    for number, line in enumerate(text.splitlines(), 1):
        for span in CODE_SPAN.finditer(line):
            for tokens in segment_invocations(span.group(1)):
                found.append((number, tokens))
        for tokens in segment_invocations(CODE_SPAN.sub(" ", line)):
            found.append((number, tokens))
    return found


def quoted_value(text, index):
    """Parse a single-line string literal; return (end index, value) or None."""
    quote = text[index]
    index += 1
    value = []
    while index < len(text):
        char = text[index]
        if char == "\\":
            index += 2
            value.append("?")
            continue
        if char == "\n":
            return None
        if char == quote:
            return index + 1, "".join(value)
        value.append(char)
        index += 1
    return None


def literal_list(text, index, identifier):
    """Parse a list of string literals and bare references from ``index``.

    Returns (end index, [(is_string, value), ...]) or None. This is a small
    linear scanner instead of a nested regular expression so large skill
    scripts stay cheap to check.
    """
    values = []
    index += 1
    while index < len(text):
        while index < len(text) and text[index].isspace():
            index += 1
        if index >= len(text):
            return None
        if text[index] == "]":
            return (index + 1, values) if values else None
        if text[index] in "\"'":
            parsed = quoted_value(text, index)
            if parsed is None:
                return None
            index, value = parsed
            values.append((True, value))
        else:
            match = identifier.match(text, index)
            if not match:
                return None
            values.append((False, match.group(0)))
            index = match.end()
        while index < len(text) and text[index].isspace():
            index += 1
        if index < len(text) and text[index] == ",":
            index += 1
        elif index >= len(text) or text[index] != "]":
            return None
    return None


def argument_lists(text, python=False):
    """Return (line number, [(is_string, value), ...]) for literal lists.

    Only plain lists of string literals and bare references are considered;
    anything else (expressions, nested arrays, concatenation) is skipped.
    """
    identifier = PY_IDENTIFIER if python else JS_IDENTIFIER
    starts = [0]
    for match in re.finditer("\n", text):
        starts.append(match.end())
    found = []
    index = 0
    while True:
        index = text.find("[", index)
        if index < 0:
            break
        parsed = literal_list(text, index, identifier)
        if parsed is None:
            index += 1
            continue
        end, values = parsed
        found.append((bisect.bisect_right(starts, index), values))
        index = end
    return found


def known_commands(surface):
    """Recorded command paths plus paths that only exist in a newer Paseo."""
    commands = dict(surface["commands"])
    for path in VERSION_GATED_COMMANDS:
        commands.setdefault(path, [])
    return commands


def command_prefixes(commands):
    prefixes = set()
    for path in commands:
        parts = path.split(" ")
        for size in range(1, len(parts)):
            prefixes.add(" ".join(parts[:size]))
    return prefixes


def resolve_command(tokens, commands):
    """Return the longest command path and how many tokens it consumed.

    A global option may precede the command (``paseo --host X host ls``), so
    resolution starts at the first token that is a known root command.
    """
    roots = {path.split(" ", 1)[0] for path in commands}
    prefixes = command_prefixes(commands)
    start = None
    for index, token in enumerate(tokens):
        if token in roots:
            start = index
            break
    if start is None:
        return "", 0
    path = ""
    consumed = start
    for index in range(start, min(start + 3, len(tokens))):
        token = tokens[index]
        if token.startswith("-") or token in ELLIPSIS:
            break
        candidate = " ".join(tokens[start:index + 1])
        if candidate not in commands and candidate not in prefixes:
            break
        if candidate in commands:
            path = candidate
            consumed = index + 1
    return path, consumed


def flag_name(token):
    token = token.split("=", 1)[0]
    return token if FLAG.match(token) else None


def flag_problems(path, flags, surface):
    valid = set(surface["globalOptions"])
    if path:
        valid.update(surface["commands"].get(path, []))
    problems = []
    for flag in flags:
        if flag in valid or (path, flag) in VERSION_GATED_FLAGS:
            continue
        label = "paseo " + path if path else "paseo"
        problems.append("flag '" + flag + "' is not defined for '" + label + "'")
    return problems


def invocation_problems(tokens, surface):
    """Check one documented invocation: command path and every flag."""
    tokens = [token for token in tokens if token not in ELLIPSIS]
    if not tokens:
        return []
    commands = known_commands(surface)
    path, consumed = resolve_command(tokens, commands)
    if path in VERSION_GATED_COMMANDS:
        return []
    following = tokens[consumed] if consumed < len(tokens) else None
    if (path and path in command_prefixes(commands) and following is not None
            and not following.startswith("-") and re.fullmatch(r"[a-z][a-z-]*", following)):
        # A command group takes a subcommand, not an argument.
        return ["unknown subcommand '" + following + "' for 'paseo " + path + "'"]
    if not path:
        first = next((token for token in tokens if not token.startswith("-")), None)
        if first is not None:
            return ["unknown command '" + first + "'"]
    flags = [flag for flag in (flag_name(token) for token in tokens) if flag]
    return flag_problems(path, flags, surface)


def script_array_problems(values, surface):
    """Check one literal argument array; ignore arrays that are not CLI args."""
    leading = []
    for is_string, value in values:
        if not is_string or value.startswith("-"):
            break
        leading.append(value)
    if not leading:
        return []
    path, _ = resolve_command(leading, known_commands(surface))
    if not path or path in VERSION_GATED_COMMANDS:
        return []
    flags = [flag for flag in (flag_name(value) for is_string, value in values
                               if is_string) if flag]
    return flag_problems(path, flags, surface)


def document_paths(root=ROOT):
    skills = root / "skills"
    found = list(skills.glob("*/SKILL.md"))
    found.extend(path for path in skills.glob("*/references/**/*.md") if path.is_file())
    return sorted(set(found))


def script_paths(root=ROOT):
    found = [path for path in (root / "skills").glob("*/scripts/*")
             if path.is_file() and path.suffix in SCRIPT_SUFFIXES]
    found.extend(path for path in (root / "plugin").glob("server/*")
                 if path.is_file() and path.suffix in SCRIPT_SUFFIXES)
    return sorted(set(found))


def collect_problems(root=ROOT, surface=None):
    surface = surface or load_surface(root / "docs" / "paseo-cli-surface.json")
    problems = []
    for path in document_paths(root):
        text = path.read_text(encoding="utf-8")
        for line, tokens in document_invocations(text):
            for message in invocation_problems(tokens, surface):
                problems.append(str(path.relative_to(root)) + ":" + str(line) + ": " +
                                message + " in 'paseo " + " ".join(tokens) + "'")
    for path in script_paths(root):
        text = path.read_text(encoding="utf-8")
        if not CLI_EVIDENCE.search(text):
            continue
        for line, values in argument_lists(text, python=path.suffix == ".py"):
            for message in script_array_problems(values, surface):
                rendered = " ".join(value for _, value in values)
                problems.append(str(path.relative_to(root)) + ":" + str(line) + ": " +
                                message + " in [" + rendered + "]")
    return problems


class ExtractorTests(unittest.TestCase):
    def setUp(self):
        self.surface = load_surface()

    def test_snapshot_shape(self):
        self.assertIn("paseoVersion", self.surface)
        self.assertTrue(self.surface["commands"])
        self.assertIn("--json", self.surface["globalOptions"])

    def test_documented_invocations(self):
        found = document_invocations(
            "Run `paseo agent ls -a` then `paseo workspace ls --json`.")
        self.assertEqual([tokens for _, tokens in found],
                         [["agent", "ls", "-a"], ["workspace", "ls", "--json"]])

    def test_hosts_cli_passthrough(self):
        found = document_invocations(
            "python3 scripts/hosts.py cli HOST -- agent inspect AGENT_ID --json")
        self.assertEqual(found, [(1, ["agent", "inspect", "AGENT_ID", "--json"])])
        self.assertEqual(invocation_problems(found[0][1], self.surface), [])

    def test_ignores_names_urls_and_prose(self):
        text = ("Use the `paseo-share` skill and https://paseo.sh/docs/cli.md. "
                "The Paseo app stays open; `paseo` alone is a tool name.")
        self.assertEqual(document_invocations(text), [])

    def test_ellipsis_and_global_flags(self):
        found = document_invocations("Installed `paseo ... --help` and `paseo --version`.")
        self.assertEqual([tokens for _, tokens in found], [["--help"], ["--version"]])
        for _, tokens in found:
            self.assertEqual(invocation_problems(tokens, self.surface), [])

    def test_rejects_unknown_command(self):
        self.assertEqual(invocation_problems(["frobnicate", "now"], self.surface),
                         ["unknown command 'frobnicate'"])

    def test_rejects_unknown_subcommand(self):
        self.assertEqual(invocation_problems(["workspace", "lst", "--json"], self.surface),
                         ["unknown subcommand 'lst' for 'paseo workspace'"])
        self.assertEqual(invocation_problems(["workspace", "ls", "--json"], self.surface), [])

    def test_global_option_before_command(self):
        tokens = ["--host", "<controller>", "host", "add", "<endpoint>", "--label", "NAME"]
        self.assertEqual(invocation_problems(tokens, self.surface), [])
        self.assertEqual(
            invocation_problems(["--json", "workspace", "ls", "--bogus"], self.surface),
            ["flag '--bogus' is not defined for 'paseo workspace ls'"])

    def test_rejects_unknown_flag(self):
        problems = invocation_problems(["daemon", "status", "--format", "json", "--bogus"],
                                       self.surface)
        self.assertEqual(len(problems), 1)
        self.assertIn("--bogus", problems[0])

    def test_accepts_recorded_flags(self):
        self.assertEqual(
            invocation_problems(["script", "ls", "--cwd", "<path>", "--json"], self.surface),
            [])
        self.assertEqual(invocation_problems(["workspace", "archive", "ID", "--json"],
                                             self.surface), [])

    def test_script_arrays(self):
        text = ('const args = kind === "agent" ? ["archive", id, "--json"] : '
                '["workspace", "archive", id, "--json"];\n')
        arrays = argument_lists(text)
        self.assertEqual([values for _, values in arrays], [
            [(True, "archive"), (False, "id"), (True, "--json")],
            [(True, "workspace"), (True, "archive"), (False, "id"), (True, "--json")],
        ])
        for _, values in arrays:
            self.assertEqual(script_array_problems(values, self.surface), [])

    def test_non_cli_arrays_are_ignored(self):
        text = 'run("git", ["--version"]); const list = ["agents", "workspaces"];\n'
        for _, values in argument_lists(text):
            self.assertEqual(script_array_problems(values, self.surface), [])

    def test_python_arrays(self):
        text = "commands = ['daemon', 'status', '--json']\n"
        arrays = argument_lists(text, python=True)
        self.assertEqual(arrays[0][1], [(True, "daemon"), (True, "status"), (True, "--json")])
        self.assertEqual(script_array_problems(arrays[0][1], self.surface), [])

    def test_plugin_worker_cli_flags_are_checked(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            worker = root / "plugin/server/update-worker.mjs"
            worker.parent.mkdir(parents=True)
            worker.write_text(
                'await execute(cli, ["plugin", "add", source, "--bogus"]);',
                encoding="utf-8")
            problems = collect_problems(root, self.surface)
        self.assertEqual(len(problems), 1)
        self.assertIn("--bogus", problems[0])


class RepositoryTests(unittest.TestCase):
    def test_snapshot_is_committed(self):
        self.assertTrue(SNAPSHOT.is_file(), "run scripts/paseo-cli-surface.py")

    def test_every_reference_resolves(self):
        problems = collect_problems()
        self.assertEqual(problems, [], "\n".join(problems))

    def test_plugin_management_arrays_are_seen(self):
        path = ROOT / "plugin" / "server" / "management.ts"
        surface = load_surface()
        self.assertTrue(CLI_EVIDENCE.search(path.read_text(encoding="utf-8")))
        resolved = []
        for _, values in argument_lists(path.read_text(encoding="utf-8")):
            leading = []
            for is_string, value in values:
                if not is_string or value.startswith("-"):
                    break
                leading.append(value)
            resolved.append(resolve_command(leading, known_commands(surface))[0])
        self.assertIn("daemon status", resolved)
        self.assertIn("plugin ls", resolved)

    def test_known_references_are_seen(self):
        surface = load_surface()
        invocations = []
        for path in document_paths():
            invocations.extend(tokens for _, tokens in
                               document_invocations(path.read_text(encoding="utf-8")))
        self.assertGreaterEqual(len(invocations), 3)
        resolved = [resolve_command(tokens, surface["commands"])[0]
                    for tokens in invocations]
        self.assertTrue(any(path in surface["commands"] for path in resolved))
        self.assertTrue(surface["commands"])


if __name__ == "__main__":
    unittest.main()
